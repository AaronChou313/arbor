export type TranslationKey = keyof typeof en;
export type ResolvedLanguage = "zh-CN" | "en-US";
type Translate = (key: TranslationKey, values?: Record<string, string | number>) => string;

export function resolveLanguage(language: LanguagePreference, browserLanguage?: string): ResolvedLanguage {
  if (language !== "auto") return language;
  const detected = browserLanguage ?? (typeof navigator === "undefined" ? "en-US" : navigator.language);
  return detected.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

function translator(language: ResolvedLanguage): Translate {
  const dictionary = language === "zh-CN" ? zh : en;
  return (key, values) => {
    let result = dictionary[key];
    for (const [name, value] of Object.entries(values ?? {})) {
      result = result.replaceAll(`{${name}}`, String(value));
    }
    return result;
  };
}

export function translate(language: ResolvedLanguage, key: TranslationKey): string {
  return translator(language)(key);
}

const defaultContext = { language: "en-US" as ResolvedLanguage, t: translator("en-US") };
const I18nContext = createContext(defaultContext);

export function I18nProvider({ language, children }: { language: LanguagePreference; children: ReactNode }) {
  const resolved = resolveLanguage(language);
  const value = useMemo(() => ({ language: resolved, t: translator(resolved) }), [resolved]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function providerErrorKey(code?: string): TranslationKey {
  const keys: Record<string, TranslationKey> = {
    NETWORK: "errorNetwork",
    CORS: "errorCors",
    AUTH: "errorAuth",
    MODEL_NOT_FOUND: "errorModel",
    RATE_LIMIT: "errorRateLimit",
    BAD_RESPONSE: "errorBadResponse",
    ABORTED: "errorAborted",
  };
  return (code && keys[code]) || "errorUnknown";
}

export function finishReasonKey(
  finishReason?: FinishReason,
  status?: NodeStatus,
): TranslationKey | null {
  if (status === "aborted") return "finishUserStopped";
  const keys: Partial<Record<FinishReason, TranslationKey>> = {
    length: "finishLength",
    "content-filter": "finishContentFilter",
    "tool-call": "finishToolCall",
    error: "finishError",
  };
  return finishReason ? keys[finishReason] ?? null : null;
}

export function testStageKey(stage: "network" | "cors" | "auth" | "model" | "unknown"): TranslationKey {
  const keys: Record<typeof stage, TranslationKey> = {
    network: "errorNetwork",
    cors: "errorCors",
    auth: "errorAuth",
    model: "errorModel",
    unknown: "errorUnknown",
  };
  return keys[stage];
}
